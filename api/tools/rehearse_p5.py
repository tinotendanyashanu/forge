"""Rehearse P4 -> P5 and two full seeds on a NEW local scratch database.

FORGE_P5_DATABASE_URL=postgresql://.../forge_p5_* venv/bin/python tools/rehearse_p5.py
Refuses a database containing public tables. Never drops a database or tables.
Creates synthetic learner history and fingerprints it before and after both seeds.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
from unittest.mock import patch
from urllib.parse import urlsplit

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import asyncpg
from fastapi.testclient import TestClient

from app.core.config import Settings
from app.main import create_app
from app.seed.__main__ import main as seed_main
from app.seed.lessons import load_lessons
from app.seed.schema import load_seed_files

ROOT = Path(__file__).resolve().parents[2]
HISTORY = ["learners", "assessment_sessions", "session_items", "answers", "evaluation_results",
           "interview_sessions", "interview_challenges", "interview_messages", "mastery_evidence",
           "skill_mastery", "mastery_events", "review_cards", "review_events", "lesson_reads"]
CONTENT = ["skills", "topics", "questions", "question_options", "skill_prerequisites"]


async def snapshot(url: str) -> dict:
    conn = await asyncpg.connect(url)
    try:
        tables = set(await conn.fetch("SELECT tablename FROM pg_tables WHERE schemaname='public'"))
        names = {r[0] for r in tables}
        result = {}
        for table in HISTORY + CONTENT + ["lessons", "lesson_questions", "lesson_resources"]:
            if table not in names:
                continue
            # Resource/link row surrogate IDs are regenerated by the existing loader.
            excluded = "" if table in HISTORY else " - 'updated_at'"
            if table in {"lesson_questions", "lesson_resources"}:
                excluded += " - 'id'"
            payload = await conn.fetchval(
                f"SELECT coalesce(jsonb_agg(row ORDER BY row::text), '[]')::text "
                f"FROM (SELECT to_jsonb(t){excluded} AS row FROM {table} t) s"
            )
            result[table] = {"count": await conn.fetchval(f"SELECT count(*) FROM {table}"),
                             "sha256": hashlib.sha256(payload.encode()).hexdigest()}
        result["counts"] = {name: await conn.fetchval(sql) for name, sql in {
            "active_questions": "SELECT count(*) FROM questions WHERE is_active",
            "inactive_questions": "SELECT count(*) FROM questions WHERE NOT is_active",
            "active_lessons": "SELECT count(*) FROM lessons WHERE is_active",
            "covered_subskills": "SELECT count(distinct (skill_id, topic_id)) FROM lessons WHERE is_active",
        }.items()}
        result["lesson_ids"] = {r["slug"]: r["id"] for r in await conn.fetch("SELECT slug, id FROM lessons")}
        return result
    finally:
        await conn.close()


def synthetic_history(url: str) -> None:
    settings = Settings().model_copy(update={"database_url": url.replace("postgresql://", "postgresql+asyncpg://"),
                                             "llm_provider": "disabled", "local_only_allowed_hosts": ["testclient"]})
    questions = {q.slug: q for f in load_seed_files() for q in f.questions}
    with TestClient(create_app(settings)) as client:
        learner = client.post("/api/v1/learners")
        assert learner.status_code == 201, learner.text
        headers = {"X-Learner-Id": learner.json()["id"]}
        for _ in range(3):
            session = client.post("/api/v1/assessments", headers=headers,
                                  json={"skill_slug": "python", "difficulty": "beginner", "question_count": 1})
            assert session.status_code == 201, session.text
            sid = session.json()["id"]
            item = client.post(f"/api/v1/assessments/{sid}/next", headers=headers).json()["item"]
            correct = next(o.text for o in questions[item["question"]["slug"]].options if o.correct)
            shown_key = next(o["key"] for o in item["question"]["options"] if o["text"] == correct)
            feedback = client.post(f"/api/v1/assessments/{sid}/answers", headers=headers,
                                   json={"item_id": item["id"], "selected_option_key": shown_key})
            assert feedback.status_code == 201, feedback.text
        done = client.post("/api/v1/lessons/tracing-program-state/complete", headers=headers)
        assert done.status_code == 200, done.text


def main() -> None:
    url = os.environ["FORGE_P5_DATABASE_URL"].replace("postgresql+asyncpg://", "postgresql://")
    target = urlsplit(url)
    assert target.hostname in {"localhost", "127.0.0.1"} and target.path.startswith("/forge_p5_")

    async def check_empty():
        conn = await asyncpg.connect(url)
        try:
            assert await conn.fetchval("SELECT count(*) FROM pg_tables WHERE schemaname='public'") == 0, "Use a NEW scratch database"
        finally:
            await conn.close()

    asyncio.run(check_empty())
    subprocess.run([sys.executable, "-m", "alembic", "-x", f"database_url={url.replace('postgresql://', 'postgresql+asyncpg://')}",
                    "upgrade", "head"], cwd=ROOT / "api", check=True, capture_output=True)
    with tempfile.TemporaryDirectory(prefix="forge-p5-baseline-") as directory:
        files = subprocess.check_output(["git", "ls-tree", "-r", "--name-only", "8062fa9", "api/app/seed/lessons"], cwd=ROOT, text=True).splitlines()
        for name in files:
            Path(directory, Path(name).name).write_bytes(subprocess.check_output(["git", "show", f"8062fa9:{name}"], cwd=ROOT))
        with patch("app.seed.__main__.load_lessons", lambda c, qs: load_lessons(c, qs, Path(directory))):
            asyncio.run(seed_main(url.replace("postgresql://", "postgresql+asyncpg://")))
    synthetic_history(url)
    before = asyncio.run(snapshot(url))
    assert before["counts"]["active_lessons"] == 15 and before["answers"]["count"] == 3
    snapshots = []
    for _ in range(2):
        asyncio.run(seed_main(url.replace("postgresql://", "postgresql+asyncpg://")))
        after = asyncio.run(snapshot(url))
        for table in HISTORY + CONTENT:
            if table in before:
                assert after[table] == before[table], f"Seed changed protected table: {table}"
        assert all(after["lesson_ids"][slug] == lesson_id for slug, lesson_id in before["lesson_ids"].items())
        assert after["counts"] == {"active_questions": 158, "inactive_questions": 0, "active_lessons": 25, "covered_subskills": 25}
        snapshots.append(after)
    assert snapshots[0] == snapshots[1], "Repeated seed changed logical content or history"
    print("P5_REHEARSAL=" + json.dumps({"baseline": before, "first_seed": snapshots[0], "second_seed": snapshots[1],
                                        "history_unchanged": True, "logical_idempotency": True}))


if __name__ == "__main__":
    main()
